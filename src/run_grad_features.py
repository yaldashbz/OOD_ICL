import argparse
import json
import numpy as np
import torch
from adaptation import load_pretrained, stack_params, batched_forward, make_direction_data

#Gradient features of the pretrained checkpoint for a run_adaptation.py --directions run, at step 0 of fine-tuning on
#exactly the same n examples of each dataset (the zero-context FT loss mean_i (f([x_i]) - y_i)^2):
#  |g_tr|                 norm of the training gradient
#  cos(g_tr, g_val)       alignment with the gradient g_val of the same loss on n_val held-out examples of the same
#                         target (paired across directions like the run's datasets)
#  cos(u_tr, g_val)       the same for Adam's first update u_tr = g_tr / (|g_tr| + eps), elementwise
#With a single token the attention weights are identically 1, so the query / key gradients are zero up to SDPA
#roundoff (~1e-9, which Adam's first step would blow up to ~0.25 against eps = 1e-8); all features use the other
#parameters, i.e. those the zero-context output depends on.
#The data are regenerated by replaying make_direction_data with the run's seed. CUDA draws depend on the GPU model,
#so the replay is checked against the saved zero-context risks and step-0 training losses before anything is saved.
parser = argparse.ArgumentParser()
parser.add_argument("--adaptation", type=str, required=True, help="adaptation_dirs_*.npz written by run_adaptation.py")
parser.add_argument("--n_val", type=int, default=1024, help="held-out examples per dataset for g_val")
parser.add_argument("--chunk", type=int, default=256, help="examples per forward pass")
parser.add_argument("--adam_eps", type=float, default=1e-8, help="eps of the fine-tuning optimizer (torch default)")
parser.add_argument("--rtol", type=float, default=1e-3)
parser.add_argument("--out", type=str, default=None)
args = parser.parse_args()

device = 'cuda'
D = np.load(args.adaptation)
a = json.loads(str(D['args']))
model, margs = load_pretrained(a['pretrained'], device)
dim = margs['dim']
data_seed = margs['seed'] if a['data_seed'] is None else a['data_seed']
sigma = np.sqrt(a['noise_var'])
data = make_direction_data(dim, margs['seq_len'], a['deltas'][0], a['directions'], a['tasks_val'], a['tasks_test'],
                           a['n_ctx'], a['n_query'], max(a['ns']), sigma, data_seed, device)
W, Xtr, Ytr = data['W'], data['Xtr'], data['Ytr'][..., 0]
E = W.shape[0]

#replay check: same tasks, same query points (R_zero), same FT examples (step-0 training loss at every n)
for k in ('member_split', 'member_direction', 'member_rep'):
    assert np.array_equal(data[k], D[k])
err_W = np.abs(W.cpu().numpy() - D['W']).max()
P0 = stack_params(model, E)
with torch.no_grad():
    zero = torch.zeros(data['Xq'].shape[:3], device=device)
    R_zero = ((batched_forward(P0, data['Xq'], zero)[..., 0] - data['Fq'][..., 0]) ** 2).mean(1).cpu().numpy()
    sq = ((batched_forward(P0, Xtr, torch.zeros(Xtr.shape[:3], device=device))[..., 0] - Ytr) ** 2).cpu().numpy()
L0 = np.stack([sq[:, :n].mean(1) for n in D['ns']])
err_zero = np.abs(R_zero / D['R_zero'] - 1).max()
err_train = np.abs(L0 / D['L_train'][:, 0, 0] - 1).max()
print("replay check: max |dW| {0:.1e}, max rel err R_zero {1:.1e}, step-0 train loss {2:.1e}".format(err_W, err_zero, err_train))
assert err_W < 1e-6 and err_zero < args.rtol and err_train < args.rtol, \
    "replayed data differ from the run's (run on the GPU model the adaptation job used)"
del data

#held-out examples from a separate generator; repetition r of a split shares its inputs and noise across directions
gen = torch.Generator(device=device)
gen.manual_seed(data_seed + 1000)
base = torch.tensor(D['member_rep'] + (D['member_split'] == "test") * a['tasks_val'], device=device)
R = a['tasks_val'] + a['tasks_test']
Xv = torch.randn(R, args.n_val, 1, dim, generator=gen, device=device)[base]
Yv = torch.einsum('end,ed->en', Xv[:, :, 0], W) + sigma * torch.randn(R, args.n_val, generator=gen, device=device)[base]

keys = [k for k in P0 if not k.endswith(('.q', '.k'))]
for k in keys:
    P0[k].requires_grad_(True)

def grad(X, Y):
    """Per-dataset gradients of the zero-context loss at the checkpoint, X: (E, m, 1, d), Y: (E, m)."""
    g = None
    for i in range(0, X.shape[1], args.chunk):
        x, y = X[:, i:i + args.chunk], Y[:, i:i + args.chunk]
        pred = batched_forward(P0, x, torch.zeros(x.shape[:3], device=device))[..., 0]
        gs = torch.autograd.grad(((pred - y) ** 2).sum() / X.shape[1], [P0[k] for k in keys])
        if g is None:
            g = dict(zip(keys, gs))
        else:
            for k, gk in zip(keys, gs):
                g[k] += gk
    return g

def dot(g, h):
    return sum((g[k].double() * h[k].double()).flatten(1).sum(1) for k in g)

g_val = grad(Xv, Yv)
norm_val = dot(g_val, g_val).sqrt()
shape = (len(D['ns']), E)
gnorm_tr, cos_val, cos_adam = np.zeros(shape), np.zeros(shape), np.zeros(shape)
for i, n in enumerate(D['ns']):
    g = grad(Xtr[:, :n], Ytr[:, :n])
    norm_tr = dot(g, g).sqrt()
    u = {k: v / (v.abs() + args.adam_eps) for k, v in g.items()}
    gnorm_tr[i] = norm_tr.cpu().numpy()
    cos_val[i] = (dot(g, g_val) / (norm_tr * norm_val)).cpu().numpy()
    cos_adam[i] = (dot(u, g_val) / (dot(u, u).sqrt() * norm_val)).cpu().numpy()
    del g, u
    test = D['member_split'] == "test"
    print("n={0:4d}: median test |g_tr| {1:.3e}, cos(g_tr, g_val) {2:.3f}, cos(u_tr, g_val) {3:.3f}".format(
        n, np.median(gnorm_tr[i, test]), np.median(cos_val[i, test]), np.median(cos_adam[i, test])), flush=True)

out = args.out or args.adaptation.replace("adaptation_", "gradfeat_")
np.savez(out, gnorm_tr=gnorm_tr, gnorm_val=norm_val.cpu().numpy(), cos_val=cos_val, cos_adam=cos_adam, L_train0=L0,
         ns=D['ns'], member_split=D['member_split'], member_direction=D['member_direction'], member_rep=D['member_rep'],
         n_val=args.n_val, replay_err=np.array([err_W, err_zero, err_train]))
print("saved", out)
